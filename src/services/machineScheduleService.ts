export function getStoredMachineSchedules(): MachineJobSchedule[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_MACHINE_SCHEDULES));
      return INITIAL_MACHINE_SCHEDULES;
    }
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : INITIAL_MACHINE_SCHEDULES;
  } catch (err) {
    console.error('Error reading machine schedules:', err);
    return INITIAL_MACHINE_SCHEDULES;
  }
}

export function saveMachineSchedules(schedules: MachineJobSchedule[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(schedules));
  } catch (err) {
    console.error('Error saving machine schedules:', err);
  }
}
